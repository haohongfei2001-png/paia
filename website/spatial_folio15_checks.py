"""V15 official Thought Library: evidence from the painted Shadow DOM, not old fallback.
Preserves every existing independent demo, input/IME, Context, privacy and R3 gate.
Only fictional user expressions, never accounts or real data.
"""
from pathlib import Path

def home(page,check,label,deep=False,out=None):
    page.wait_for_selector('body[data-atelier-ready=true]')
    page.wait_for_selector('body[data-spatial15=ready]')
    page.evaluate('document.fonts.ready')
    def ck(ok,msg):check(ok,label+': '+msg)
    shadow='#thoughts .pa15'
    h=page.locator('#thoughts')
    width=page.viewport_size['width']
    ck(h.evaluate('e=>!!e.shadowRoot'),'real official thought is rendered through Shadow DOM')
    ck(h.get_attribute('data-spatial15')=='ready','visible visual version marked V15')
    ck(page.locator('script[src*="presentation15.js"]').count()==1 and page.locator('script[src*="presentation13.js"]').count()==0,'fresh versioned runtime entry, no cached V13 URL')
    ck(page.locator('body').get_attribute('data-website-release')=='atelier-v15-20261024','public document identifies the current release')
    ck(page.locator('h1').count()==1 and page.locator('#hero-title').is_visible(),'original hero preserved')
    ck(page.locator('.word-tag').count()==4 and page.locator('#why .manifesto-body').is_visible(),'original colored words and manifesto')
    ck(page.locator('main>section').evaluate_all('es=>es.map(e=>e.id)')==['top','why','archive','thoughts','context','how','story','get-paia'],'existing page narrative order')
    ck(page.locator('#archive .p13-input').count()==4,'unchanged archive collection')
    ck(page.locator(shadow+' .pa15-topic').count()==3,'three actual topics, not decorative cards')
    ck(page.locator(shadow+' .pa15-topic p span').count()==9,'all nine existing chapters retained')
    ck(page.locator(shadow+' .pa15-story').is_visible(),'chapter is visible without operating interface')
    ck(page.locator(shadow+' .pa15-entry').count()==2,'two complete original entries')
    ck(page.locator(shadow+' .pa15-entry time').evaluate_all('es=>es.map(e=>e.getAttribute("datetime"))')==['2026-09-18T21:06','2026-09-12T10:32'],'original timestamps, newest-first')
    ck(page.evaluate('(()=>{let h=document.querySelector("#thoughts");return JSON.stringify([...h.querySelectorAll(".p13-entry-body p")].map(e=>e.textContent))===JSON.stringify([...h.shadowRoot.querySelectorAll(".pa15-entry p")].map(e=>e.textContent))})()'),'visible source text equals existing semantic source')
    ck(page.locator(shadow+' .pa15-topic input, '+shadow+' input, '+shadow+' [contenteditable]').count()==0,'no invented manual search or editing')
    ck(page.locator('#context .context-card').count()==4,'approved Context quartet untouched')
    ck(page.locator('.p13-detail-grid>.p13-detail-card').count()==3,'reuse, editing and private space retained')
    ck(page.locator('.privacy-art .privacy-ring').count()==2,'privacy orbit retained')
    ck(page.locator('#prompt-draft').get_attribute('readonly') is not None,'fictional draft remains readonly')
    ck(page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'),'no horizontal overflow')
    ck(h.evaluate('e=>e.getBoundingClientRect().height') < (1900 if width<=600 else 1500),'no 300vh empty scroll stage')
    ck(page.locator(shadow+' .pa15-story').evaluate('e=>e.getBoundingClientRect().width >= 0.58 * e.closest(".pa15-body").getBoundingClientRect().width' if width>800 else 'e=>e.getBoundingClientRect().width >= 0.80 * innerWidth'),'reading, not empty shell, is the visual focus')
    ck(page.locator(shadow+' .pa15-entry p').evaluate_all('es=>es.every(e=>parseFloat(getComputedStyle(e).fontSize)>=(innerWidth<=350?12:innerWidth<=600?13:14))'),'readable complete source words')
    if width<=800:
        ck(page.locator(shadow+' .pa15-index').evaluate('e=>e.getBoundingClientRect().height<205'),'small screens use compact topic directory')
        ck(page.locator(shadow+' .pa15-index-items').evaluate('e=>getComputedStyle(e).gridTemplateColumns.split(" ").length===3'),'three topics on one responsive row')
    ck(page.locator(shadow+' .pa15-story').evaluate('e=>{let p=e.getBoundingClientRect();return [...e.querySelectorAll(".pa15-entry p")].every(x=>x.getBoundingClientRect().right<=p.right+1)}'),'no clipped reading content')
    if page.locator('.menu-toggle').is_visible():
        menu=page.locator('.menu-toggle');menu.focus();page.keyboard.press('Enter')
        ck(page.locator('#mobile-nav').is_visible(),'keyboard menu opens')
        page.keyboard.press('Escape')
        ck(not page.locator('#mobile-nav').is_visible() and menu.evaluate('e=>e===document.activeElement'),'menu restores focus')
    page.emulate_media(reduced_motion='reduce')
    ck(page.locator(shadow+' .pa15-story').is_visible(),'reduced motion retains full reader')
    ck(page.locator(shadow+' .pa15-body').evaluate('e=>getComputedStyle(e).transform==="none"'),'reduced motion avoids perspective camera')
    if out:
        dest=Path(out);dest.mkdir(parents=True,exist_ok=True)
        page.locator('#thoughts').screenshot(path=str(dest/(label.replace('/','-')+'-folio-v15.png')),animations='disabled')
    if not deep:return
    page.emulate_media(reduced_motion='no-preference')
    nodes=page.locator(shadow+' .pa15-entry p')
    originals=nodes.all_text_contents()
    page.evaluate('window.__pa15Entries=[...document.querySelector("#thoughts").shadowRoot.querySelectorAll(".pa15-entry p")]')
    h.scroll_into_view_if_needed()
    page.evaluate('scrollBy({top:175,behavior:"instant"});dispatchEvent(new Event("scroll"))')
    page.wait_for_timeout(150)
    ck(nodes.all_text_contents()==originals,'scroll never rewrites words')
    ck(page.evaluate('window.__pa15Entries.every((e,i)=>e===document.querySelector("#thoughts").shadowRoot.querySelectorAll(".pa15-entry p")[i])'),'scroll preserves source nodes')
    ck(h.evaluate('e=>e.getBoundingClientRect().height')<(1900 if width<=600 else 1500),'scroll stage remains reasonably sized')
    page.emulate_media(reduced_motion='reduce')
    switches=page.locator('.context-switch')
    master=page.locator('#context [data-ctx-master]')
    ck(switches.evaluate_all('es=>es.every(e=>e.getAttribute("aria-checked")==="false")'),'Context permissions off by default')
    page.locator('#context [data-ctx-open=information]').first.click()
    ck(page.locator('#context-dialog').is_visible() and switches.nth(0).get_attribute('aria-checked')=='false','view content without automatic grant')
    page.keyboard.press('Escape')
    switches.nth(1).click();master.click();master.click()
    ck(switches.nth(1).get_attribute('aria-checked')=='true' and master.get_attribute('aria-checked')=='false','pause preserves narrower choice')
    page.locator('#context [data-ctx-open=inputs]').first.click()
    page.locator('[data-topic-permission=product]').click()
    ck(master.get_attribute('aria-checked')=='false' and switches.nth(3).get_attribute('aria-checked')=='false','topic choice never grants parent access')
    page.locator('[data-ctx-topic=product]').click()
    ck(page.locator('#context-dialog [contenteditable]').count()==0,'Context body remains read-only')
    page.keyboard.press('Escape')
    ck(not page.locator('#context-dialog').is_visible(),'Escape closes modal after content transition')
    draft=page.locator('#prompt-draft');draft.scroll_into_view_if_needed()
    page.locator('#r3-host .ps-anchor').click()
    ck(page.locator('#r3-host .ps-board').is_visible() and page.locator('#r3-host .ps-row').count()==6,'authentic approved R3 still opens')
    page.locator('#r3-host .ps-row button').first.click()
    ck(len(draft.input_value().splitlines())>=2,'draft insertion retains original text')
    ck(not page.evaluate('localStorage.length||sessionStorage.length'),'no visitor persistence')
    page.emulate_media(forced_colors='active')
    ck(page.locator(shadow+' .pa15-story').is_visible(),'content visible in high contrast')
    page.emulate_media(forced_colors='none')
