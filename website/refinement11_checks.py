    test(page.locator('h1').count()==1 and page.locator('h1').is_visible(),'single clear heading')
    test(page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'),'fits viewport')
    test(page.locator('.d11-space-nav a').count()==4,'all four example sections reachable')
    test(page.locator('#thought-library input,#personal-context input').count()==0,'Thought and Context search genuinely absent')
    test(page.locator('details summary').evaluate_all('es=>es.every(e=>!/来源|source/i.test(e.textContent))'),'no source disclosures')
    test(page.locator('#topic-grid .v8-topic-card').count()==3,'three actual topic directories')
    test(page.locator('#topic-grid p,#topic-grid blockquote').count()==0,'directories contain no excerpts or summaries')
    test(page.locator('#topic-prose [contenteditable]').count()>0,'direct editable thought content')
    test(page.locator('#topic-prose .v8-entry-body').evaluate_all('es=>es.every(e=>parseFloat(getComputedStyle(e).fontSize)>=14)'),'readable working text')
    test(page.locator('.context-card').count()==4,'four independent Context cards')
    test(page.locator('#personal-context [contenteditable]').count()==0,'card overview contains no private body fields')
    test(page.locator('#prompt-draft').get_attribute('readonly') is None,'example draft is genuinely editable')
    test(page.locator('#ax-reading').inner_text()=='','fresh archive does not choose for the visitor')
    test(page.locator('#archive-empty').is_visible(),'empty selection is explained')
    if out:
        dest=Path(out);dest.mkdir(parents=True,exist_ok=True);page.emulate_media(reduced_motion='reduce')
        page.evaluate("scrollTo({top:0,behavior:'instant'})")
        page.screenshot(path=str(dest/(label.replace('/','-')+'-demo.png')),animations='disabled')
    if not deep:return
    # Expansion is not selection. Query searches actual working wording.
    page.locator('.d11-project summary').first.click()
    test(page.locator('#ax-reading').inner_text()=='','group expansion leaves reading pane empty')
    query=page.locator('#ax-query');query.fill('第一步' if zh else 'first step')
    test(page.locator('#ax-results [data-archive-target]').count()>=1,'input search finds matching actual wording')
    page.locator('#ax-results [data-archive-target=product-first]').click()
    test(page.locator('#ax-reading h3').evaluate('e=>e===document.activeElement'),'result selection moves keyboard focus to the document')
    field=page.locator('#ax-reading [contenteditable]');original=field.inner_text()
    unsafe='<img src=x onerror="window.__injected=true"> A synthetic sentence.'
    field.fill(unsafe)
    test(page.locator('#ax-reading img').count()==0 and not page.evaluate('Boolean(window.__injected)'),'edited markup remains text')
    query.fill('synthetic sentence')
    test(page.locator('#ax-results [data-archive-target=product-first]').count()==1,'search includes current working edits')
    page.locator('#ax-results [data-archive-target=product-first]').click()
    test(page.locator('#ax-reading [contenteditable]').inner_text()==unsafe,'working edit retained on revisit')
    # Archive and Thought use distinct working layers, with preset invalidation.
    page.locator('#topic-grid [data-topic=product][data-section="1"]').click()
    test(page.locator('#topic-prose [data-edit-id=product-first]').inner_text()==unsafe,'linked working text updates the thought view')
    page.locator('#organize-gallery').click()
    test(('已失效' if zh else 'out of date') in page.locator('#topic-prose .v8-ai-note').inner_text(),'edited inputs invalidate the prerecorded derivative')
    test(page.locator('#topic-prose [contenteditable]').count()==0,'preset derivative remains read-only')
    page.locator('#organize-gallery').click()
    page.locator('#topic-prose [data-edit-id=product-first]').fill('My thought-only revision.')
    test(page.locator('#ax-reading [contenteditable]').inner_text()==unsafe,'thought editing does not overwrite input working text')
    page.locator('#writing-end').fill('An additional thought.')
    page.locator('#topic-grid [data-topic=travel][data-section="0"]').click()
    page.locator('#topic-grid [data-topic=product][data-section="1"]').click()
    test(page.locator('#writing-end').inner_text()=='An additional thought.','additional note survives chapter navigation')
    test(page.locator('#topic-prose [data-edit-id=product-first]').inner_text()=='My thought-only revision.','direct thought edit survives navigation')
