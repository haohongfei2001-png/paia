from pathlib import Path
import hashlib,json,re

def static(root,check):
    baseline=json.loads((root/'website/atelier/preserved-v11.json').read_text())
    for path,digest in baseline['files'].items():
        check(hashlib.sha256((root/path).read_bytes()).hexdigest()==digest,'V11 retained exact: '+path)
    for lang,prefix in [('en',''),('zh','zh/')]:
        home=(root/(prefix+'index.html')).read_text();demo=(root/(prefix+'demo.html')).read_text()
        check('data-atelier-version="11"' in home,prefix+': V11 home')
        check('data-atelier-demo="11"' in demo,prefix+': current matching example')
        check(home.count('class="p10-thought-line ')==3,prefix+': same three expressions retained')
        check(home.count('p11-chapter-label')==3,prefix+': chapter hierarchy instead of a second control panel')
        check(home.count('class="context-card ')==4 and demo.count('class="context-card ')==4,prefix+': same four-card product model')
        check('presentation11.js' in home and 'presentation10.js' not in home,prefix+': one homepage motion controller')
        check('data-open-source' not in home and 'data-view-source' not in home,prefix+': no source actions in presentation')
        check(not any(v in demo for v in ['data-topic-search','data-reading-style','pc-topic-source','pc-source','查看来源','原始来源','View source']),prefix+': obsolete search/source/reading-mode UI removed, not hidden')
        check('id="ax-query"' in demo and 'id="section-nav"' in demo,prefix+': archive search and real Section navigation retained')
        check(all('id="'+x+'"' in demo for x in ['input-library','thought-library','prompt-reuse','personal-context']),prefix+': existing product deep links preserved')
        check('data-working' not in demo,prefix+': no two competing demo controllers')
        check('data-edit-id="product-first"' in demo,prefix+': complete static example content')
        for asset in [f'demo11.{lang}.js','presentation11.js']:
            text=(root/'assets/website/atelier'/asset).read_text()
            check(not re.search(r'\b(fetch|XMLHttpRequest|sendBeacon|WebSocket)\s*\(',text),asset+': no transport')
            check(not re.search(r'\b(localStorage|sessionStorage)\b',text),asset+': no persistence')
    js=(root/'assets/website/atelier/presentation11.js').read_text()
    check('subjectVisible' in js and 'const readable=' in js,'V11 subject visibility controls the start')
    check('manualFloat=true' in js and 'visibilitychange' in js and 'prefers-reduced-motion' in js,'V11 motion retains manual/hidden/reduced handling')
    approved=root/'extension/docs/consumer-product-v1/design/narrow-input-board-v4/fusion-r3-2026-10-18'
    for f in ['component.js','fusion.js']:
        check((approved/f).read_bytes()==(root/'assets/website/atelier'/('r3-'+f)).read_bytes(),'V11 exact approved R3 '+f)

